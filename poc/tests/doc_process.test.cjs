/** Sustainable document-process checks: one status source, immutable provenance, no silent loss. */
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const cp=require('node:child_process');
const root=path.resolve(__dirname,'../..');
const load=p=>fs.readFileSync(path.join(root,p),'utf8');
const execute=(file,args=[])=>cp.execFileSync(process.execPath,[file,...args],{cwd:root,encoding:'utf8'});
const git=(...args)=>cp.execFileSync('git',args,{cwd:root,encoding:'utf8'});
const exists=(sha,p)=>{try{git('cat-file','-e',sha+':'+p);return true}catch{return false}};
const localRefsMasked=s=>s.replace(/(!?\[[^\]\n]*\]\()([^\s)]+)([^)\n]*\))/g,(all,a,u,tail)=>{
 if(/^(?:[a-z][\w+.-]*:|\/\/|#)/i.test(u))return all;
 return a+'__REBASED_LOCAL_URL__'+tail;
}).replace(/^(\s{0,3}\[[^\]\n]+\]:\s*)(\S+)/gm,(all,a,u)=>{
 if(/^(?:[a-z][\w+.-]*:|\/\/|#)/i.test(u))return all;
 return a+'__REBASED_LOCAL_URL__';
});
