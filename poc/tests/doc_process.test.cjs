test('each split original is preserved under Git provenance, apart from relative link relocation',()=>{
 const manifest=JSON.parse(load('docs/evidence/quality/doc-split-provenance-20261110.json'));
 assert.equal(manifest.schemaVersion,1);
 assert.match(manifest.sourceCommit,/^[0-9a-f]{40}$/);
 assert.equal(manifest.snapshots.length,3);
 for(const entry of manifest.snapshots){
  assert.ok(fs.existsSync(path.join(root,entry.snapshotPath)),entry.snapshotPath);
  assert.equal(git('rev-parse',manifest.sourceCommit+':'+entry.sourcePath).trim(),entry.sourceBlobSha);
  const original=git('show',manifest.sourceCommit+':'+entry.sourcePath);
  const snapshot=load(entry.snapshotPath);
  assert.equal(localRefsMasked(snapshot),localRefsMasked(original),entry.snapshotPath+' prose was changed');
 }
});
