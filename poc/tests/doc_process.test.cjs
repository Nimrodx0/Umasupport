test('each owner decision has a source, defensible editorial state and direct successor',()=>{
 const reg=JSON.parse(load('docs/decisions/registry.json'));
 assert.equal(reg.schemaVersion,2);
 assert.equal(reg.entries.length,40);
 assert.equal(reg.documentEntries.length,2);
 assert.match(reg.assessment.type,/editorial/i);
 const items=[...reg.entries,...reg.documentEntries];
 const ids=new Set(items.map(x=>x.id));
 assert.equal(ids.size,items.length,'IDs must be unique');
 const allowed=new Set(reg.allowedStatuses);
 for(const e of items){
  assert.ok(allowed.has(e.status),e.id);
  assert.ok(fs.existsSync(path.join(root,e.sourcePath)),e.id+' missing source');
  if(e.status==='review-required'){
   assert.equal(e.reviewedAt,null,e.id+' not confirmed');
   assert.equal(e.assessmentBasis,null,e.id+' no fabricated evidence');
  }else{
   assert.match(e.reviewedAt,/^\d{4}-\d\d-\d\d$/,e.id);
   assert.ok(e.assessmentBasis && e.assessmentBasis.startsWith('docs/decisions/log.md#'),e.id);
  }
  for(const next of e.relation){
   assert.ok(ids.has(next),e.id+' unknown successor '+next);
   assert.ok(load('docs/decisions/index.md').includes(']('+'#'+next.toLowerCase()+')'),
    e.id+' link must resolve directly to successor '+next);
  }
 }
 assert.ok(reg.documentEntries.some(x=>x.sourcePath.endsWith('card-image-rights-decision.md')));
 assert.ok(reg.documentEntries.some(x=>x.sourcePath.endsWith('event-data-acquisition-rights-20261019.md')));
});
