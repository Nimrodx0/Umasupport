#!/usr/bin/env node
'use strict';
/** One source of truth: docs/decisions/registry.json. This file renders the read-only index. */
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const file=path.join(root,'docs/decisions/index.md');
const registry=JSON.parse(fs.readFileSync(path.join(root,'docs/decisions/registry.json'),'utf8'));
const renderDecisionIndex=function renderDecisionIndex(reg){
 const esc=s=>String(s??"").replaceAll("|","\\|").replace(/\r?\n/g," ");
 const entries=reg.entries,states=reg.allowedStatuses,counts=Object.fromEntries(states.map(st=>[st,entries.filter(e=>e.status===st).length]));
 const source=(e)=>e.sourcePath==="docs/decisions/log.md"?"log.md#"+e.sourceAnchor:e.sourcePath.replace(/^docs\/decisions\//,"");
 const title="# 意思決定の状態別索引\n\n<!-- GENERATED by node poc/tools/build_decision_index.cjs --write. Do not edit by hand. -->\n\n"
 + "このファイルは[唯一の状態管理台帳](registry.json)から生成されます。判断の原文は[判断ログ](log.md)または個別の出典文書が正本です。`current`は過去記録からの**編集上の判定**であり、利用者による今回の再承認・実装完了・公開許可を意味しません。最新の有効要件は[requirements](../reference/requirements.md)、実装の検証結果は[status](../project/status.md)を参照します。\n\n"
 + "状態：`current`（確認された最新の判断）、`superseded`（明示的に置換）、`qualified`（後続判断で一部限定）、`review-required`（適用状態未確定）。いずれも原文を消したり実装を自動変更するものではありません。\n\n"
 + "**ログ40件の状態**："+states.map(st=>`${st} ${counts[st]}件`).join("、")+"。独立した判断文書 "+reg.documentEntries.length+"件は別集計です。\n\n";
 const rows=entries.map(e=>{
  const succ=e.relation.map(id=>`[${id}](#${id.toLowerCase()})`).join("、");
  return `| <a id="${e.id.toLowerCase()}"></a>[${e.id} ${esc(e.heading)}](${source(e)}) | \`${e.status}\` | ${succ||"なし"} | ${esc(e.note)} |`;
 }).join("\n");
 const standalone=reg.documentEntries.map(e=>`| <a id="${e.id.toLowerCase()}"></a>[${e.id} ${esc(e.heading)}](${source(e)}) | \`${e.status}\` | ${esc(e.note)} |`).join("\n");
 return title+
 "## ログ内の判断\n\n| ID・判断原文 | 状態 | 後続判断（直接参照） | 適用範囲・留保 |\n| --- | --- | --- | --- |\n"+rows+
 "\n\n## 独立した判断資料\n\n| ID・原文 | 状態 | 適用範囲・留保 |\n| --- | --- | --- |\n"+standalone+
 "\n\n## 状態を変更するには\n\n"
 + "原文と明示的な後続判断を照合し、[registry.json](registry.json)の状態・置換先ID・判定根拠・確認日を修正した後、`node poc/tools/build_decision_index.cjs --write`で生成し直します。`review-required`は未調査であって撤回ではありません。技術的な採用理由と代替案は[ADR](../adr/README.md)で別途記録します。\n";
};
const output=renderDecisionIndex(registry);
if(process.argv.includes('--write')){fs.writeFileSync(file,output);console.log('Generated '+path.relative(root,file));}
else if(process.argv.includes('--check')){
 const actual=fs.readFileSync(file,'utf8');
 if(actual!==output){console.error('Decision index differs from registry. Run node poc/tools/build_decision_index.cjs --write');process.exitCode=1;}
 else console.log('Decision index matches registry ('+(registry.entries.length+registry.documentEntries.length)+' records)');
}else process.stdout.write(output);
